import { chromium, expect } from '@playwright/test'
import { existsSync, writeFileSync, readFileSync, unlinkSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
const [baseURL, route, firstRoot, secondRoot] = process.argv.slice(2)
if (![baseURL, route, firstRoot, secondRoot].every(Boolean)) throw new Error('missing fixture arguments')
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext()
const evidence = process.env.CHORA_CLOSURE_SCREENSHOTS
if (evidence) { mkdirSync(evidence, {recursive:true}); await context.tracing.start({screenshots:true,snapshots:true,sources:true}) }
try {
 const page = await context.newPage()
 await page.goto(baseURL+route)
 const panel = page.getByRole('region',{name:'Close remaining results',exact:true})
 await expect(panel.getByRole('button',{name:'Preview close',exact:true})).toBeVisible()
 await panel.getByRole('button',{name:'Preview close',exact:true}).click()
 await expect(panel.getByRole('button',{name:'Confirm close',exact:true})).toBeVisible()
 if (!existsSync(firstRoot)||!existsSync(secondRoot)) throw new Error('preview removed worktree')
 await panel.getByRole('button',{name:'Confirm close',exact:true}).click()
 await expect(panel.getByText('Remaining results closed',{exact:true})).toBeVisible()
 await expect(panel.getByRole('button',{name:'Preview cleanup',exact:true})).toHaveCount(2)
 if (!existsSync(firstRoot)||!existsSync(secondRoot)) throw new Error('close removed worktree')
 const entries = panel.locator(':scope > ul > li')
 await entries.nth(0).getByRole('button',{name:'Preview cleanup',exact:true}).click()
 await expect(entries.nth(0).getByRole('group')).toContainText(firstRoot)
 await expect(entries.nth(0).getByRole('group')).toContainText('same.txt')
 const extra = join(firstRoot,'user-extra.txt')
 writeFileSync(extra,'preserve user extra\n')
 await entries.nth(0).getByRole('button',{name:'Confirm cleanup',exact:true}).click()
 await expect(entries.nth(0).getByRole('button',{name:'Preview cleanup again',exact:true})).toBeVisible()
 if(readFileSync(extra,'utf8')!=='preserve user extra\n') throw new Error('extra file lost')
 unlinkSync(extra)
 await entries.nth(0).getByRole('button',{name:'Preview cleanup again',exact:true}).click()
 await entries.nth(0).getByRole('button',{name:'Confirm cleanup',exact:true}).click()
 await expect(entries.nth(0)).toContainText('Cleaned')
 if(existsSync(firstRoot)||!existsSync(secondRoot)) throw new Error('partial cleanup isolation failed')
 if(evidence) await panel.screenshot({path:join(evidence,'partial-cleanup.png')})
 await page.reload()
 await expect(panel.locator(':scope > ul > li').nth(0)).toContainText('Cleaned')
 await entries.nth(1).getByRole('button',{name:'Preview cleanup',exact:true}).click()
 await entries.nth(1).getByRole('button',{name:'Confirm cleanup',exact:true}).click()
 await expect(entries.nth(1)).toContainText('Cleaned')
 await page.reload()
 await expect(panel.locator(':scope > ul > li')).toHaveCount(2)
 await expect(panel.getByRole('button',{name:'Preview cleanup',exact:true})).toHaveCount(0)
 await expect(entries.nth(0)).toContainText('Cleaned')
 await expect(entries.nth(1)).toContainText('Cleaned')
 if(existsSync(firstRoot)||existsSync(secondRoot)) throw new Error('cleanup incomplete')
 if(evidence) await panel.screenshot({path:join(evidence,'all-cleaned.png')})
 process.stdout.write('RESULT_CLOSURE_BROWSER_PASS\n')
} finally {
 if(evidence) await context.tracing.stop({path:join(evidence,'trace.zip')})
 await browser.close()
}
