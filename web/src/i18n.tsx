function interpolate(value: string, values: Values = {}) {
  return Object.entries(values).reduce((result, [key, replacement]) => result.replaceAll(`{${key}}`, String(replacement)), value)
}

const I18nContext = createContext<I18n>({ locale: 'en', setLocale: () => {}, t: (english, values) => interpolate(english, values) })

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => window.localStorage.getItem(storageKey) === 'zh-CN' ? 'zh-CN' : 'en')
  const setLocale = useCallback((next: Locale) => {
    window.localStorage.setItem(storageKey, next)
    setLocaleState(next)
  }, [])
  useEffect(() => { document.documentElement.lang = locale }, [locale])
  const t = useCallback((english: string, values?: Values) => interpolate(locale === 'zh-CN' ? zhCN[english] ?? english : english, values), [locale])
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() { return useContext(I18nContext) }
